(async () => {
  const fs = await import('node:fs');
  const path = await import('node:path');
  const { execSync } = await import('node:child_process');

  const cwd = process.cwd();
  const root = cwd;
  if (!fs.existsSync(path.join(root, 'package.json')) || !fs.existsSync(path.join(root, 'src'))) {
    console.error('Galat folder! Ye script dashboard-website-main/ (jahan package.json aur src/ hai) mein chalao.');
    process.exit(1);
  }

  const backupDir = path.join(root, '_backup_before_update');
  const install = process.argv.includes('--install');
  const keepIfExists = ['.env'];
  let created = 0, updated = 0, skipped = 0, backedUp = 0;

  for (const [rel, content] of Object.entries(files)) {
    const full = path.join(root, rel);
    fs.mkdirSync(path.dirname(full), { recursive: true });
    const exists = fs.existsSync(full);

    if (exists && keepIfExists.includes(rel)) {
      console.log('SKIP    (pehle se hai, chhua nahi):', rel);
      skipped++;
      continue;
    }

    if (exists) {
      const old = fs.readFileSync(full, 'utf8');
      if (old === content) {
        console.log('SAME    :', rel);
        skipped++;
        continue;
      }
      // Purani file ka backup (sirf pehli baar)
      const bak = path.join(backupDir, rel);
      if (!fs.existsSync(bak)) {
        fs.mkdirSync(path.dirname(bak), { recursive: true });
        fs.writeFileSync(bak, old);
        backedUp++;
      }
      fs.writeFileSync(full, content);
      console.log('UPDATED :', rel, '(purani file backup mein)');
      updated++;
    } else {
      fs.writeFileSync(full, content);
      console.log('CREATED :', rel);
      created++;
    }
  }

  console.log('\nDone! ' + created + ' nayi, ' + updated + ' update, ' + skipped + ' same/skip.');
  if (backedUp) console.log('Purani files yahan hain: ' + backupDir);

  if (install) {
    console.log('\nnpm install react-router-dom@6 chal raha hai...');
    execSync('npm install react-router-dom@6', { cwd: root, stdio: 'inherit' });
  }

  console.log('\nAb ye karo:');
  if (!install) console.log('  1) npm install react-router-dom@6');
  console.log('  ' + (install ? '1' : '2') + ') Backend chalao (alag terminal): cd backend && npm run seed && npm run dev');
  console.log('  ' + (install ? '2' : '3') + ') Frontend chalao: npm run dev   (.env badla ho to restart zaroori)');
  console.log('  ' + (install ? '3' : '4') + ') Browser: http://localhost:5173/dashboard-website/  ->  login: admin@dashboard.com / admin123');
})();
